import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium,firefox} from 'playwright';
import {browserLaunchOptions,browserContextOptions} from './browser-environment.mjs';
import {installPrivacyGuard} from './privacy-network.mjs';
import {nativeNetwork} from './network-route-fixture.mjs';

const engine=process.env.ICM_BROWSER||'chromium';
const base=process.env.ICM_BASE_URL||'http://127.0.0.1:8000/';
const evidence=process.env.ICM_EVIDENCE_DIR||'/tmp/hydra-route-evidence';
const baseline=process.env.ICM_ROUTE_BASELINE==='1';
const browser=await (engine==='firefox'?firefox:chromium).launch(browserLaunchOptions());
const context=await browser.newContext({...browserContextOptions(),viewport:{width:1440,height:1000},reducedMotion:'reduce',acceptDownloads:true});
const page=await context.newPage();
const privacy=installPrivacyGuard(context,base);
const errors=[];
page.on('pageerror',error=>{errors.push(error.message);console.error('Browser error:',error.message);});
const file=(name,text)=>({name,mimeType:'text/csv',buffer:Buffer.from(text)});
const snapshot=()=>page.evaluate(()=>window.ICMNetworkSchematic.snapshot());
const networkPage=()=>page.evaluate(()=>window.__ICM_PRECISION_WORKBENCH__.navigate('network','schematic',true));
await fs.mkdir(evidence,{recursive:true});
try{
  const boot=performance.now();
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>window.__ICM_PRECISION_WORKBENCH__?.navigate);
  const startup=performance.now()-boot;
  const measure=performance.now();
  await networkPage();
  await page.locator('#nsEdit').waitFor();
  const firstSchematic=performance.now()-measure;
  await page.setInputFiles('#nsLoadInput',file('network.csv',nativeNetwork));
  await page.locator('#nsContextUnits').check();
  await page.click('#nsContextApply');
  await page.waitForFunction(()=>window.ICMNetworkSchematic.snapshot().edges.length===7);
  await page.locator('[data-ns-node="00127"]').press('Enter');
  await page.click('#nsInspectorTab-properties');
  for(const width of [1440,1024,720]){
    await page.setViewportSize({width,height:1000});
    await page.locator('#nsPopup').scrollIntoViewIfNeeded();
    await page.screenshot({path:evidence+'/'+engine+'-'+(baseline?'before':'after')+'-properties-'+width+'.png'});
  }
  await page.setViewportSize({width:1440,height:1000});
  if(!baseline){
    await page.evaluate(()=>window.__ICM_PRECISION_WORKBENCH__.navigate('data','time-series',true));
    await page.setInputFiles('#fileInput',file('synthetic-model.csv','timestamp,Level (m)\n2024-01-01T00:00:00,10.2\n2024-01-01T00:15:00,10.25\n2024-01-01T00:30:00,10.24\n'));
    await page.waitForFunction(()=>[...state.files.values()].some(file=>file.status==='ready'),null,{timeout:120000});
    await page.click('#pwImportMonitorLocations');
    await page.setInputFiles('#nsMonitorFile',file('locations.csv','Column 1,Column 2\n00127,FM-01\nB.1,FM-02\nB.1,FM-03\nmissing,FM-04\n'));
    await page.selectOption('#nsMonitorNameColumn','1');
    assert.match(await page.locator('#nsMonitorPreview').innerText(),/Ambiguous/);
    assert.match(await page.locator('#nsMonitorPreview').innerText(),/Unmatched/);
    for(const row of [3,4]){
      const selector=page.getByRole('combobox',{name:'Choose installed asset for row '+row});
      const value=await selector.locator('option').filter({hasText:'Link ·'}).getAttribute('value');
      await selector.selectOption(value);
    }
    await page.click('#nsMonitorApply');
    assert.match(await page.locator('#nsMonitorMessage').innerText(),/3 applied · 1 unresolved/);
    await page.click('#nsMonitorClose');
    await networkPage();
    assert.equal(await page.locator('#nsSvg [data-ns-monitor]').count(),2);
    await page.locator('[data-ns-node="B"]').press('Enter');
    await page.click('#nsEdit');
    await page.click('#nsDrawer [data-ns-add-sources="model"]');
    await page.locator('#nsPicker .ns-file-list input').check();
    await page.click('#nsAddSelected');
    const datum=page.locator('#nsDrawer [data-ns-binding-field="datum"]');
    await datum.fill('AOD');await datum.dispatchEvent('change');
    await page.click('#nsEdit');
    const camera=(await snapshot()).camera;
    await page.uncheck('#nsShowLabels');
    assert.equal(await page.locator('#nsSvg [data-ns-label],#nsSvg [data-ns-edge-label]').count(),0);
    assert.deepEqual((await snapshot()).camera,camera);
    assert.equal(await page.locator('#nsSvg [data-ns-monitor]').count(),2);
    await page.uncheck('#nsShowMonitors');
    assert.equal(await page.locator('#nsSvg [data-ns-monitor]').count(),0);
    await page.check('#nsShowMonitors');
    await page.click('#nsOverview');
    assert.equal(await page.locator('#nsOverview').getAttribute('aria-pressed'),'true');
    await page.click('#nsLongSection');
    await page.selectOption('#nsRouteStart','00127');
    await page.selectOption('#nsRouteEnd','E');
    assert(await page.locator('#nsOpenProfile').isDisabled());
    const edges=(await snapshot()).edges;
    const get=name=>edges.find(edge=>edge.name===name).id;
    await page.selectOption('#nsRouteBranch select',get('B.1'));
    await page.click('#nsOpenProfile');
    assert.match(await page.locator('#nsProfileRows').innerText(),/100 → 220/);
    assert.match(await page.locator('#nsProfileRows').innerText(),/Missing length · Missing invert/);
    await page.locator('.ns-model-overlay summary').click();
    await page.locator('#nsProfileModelForm [name="scenario"]').fill('Baseline');
    await page.locator('#nsProfileModelForm [name="time"]').fill('2024-01-01T00:15');
    await page.locator('#nsProfileModelForm [name="datum"]').fill('AOD');
    await page.click('#nsApplyModelLevels');
    await page.waitForFunction(()=>document.getElementById('nsModelLevelsMessage').textContent.includes('1 route node samples'),null,{timeout:90000});
    assert.match(await page.locator('#nsProfileModelInfo').innerText(),/Baseline.*AOD/);
    await page.locator('#nsProfileRows button').first().click();
    assert.equal(await page.locator('#nsProfileRows button').first().getAttribute('aria-pressed'),'true');
    await page.click('#nsProfileCapacity');
    assert.equal(await page.locator('#nsCapacityForm [name="diameter"]').inputValue(),'600');
    await page.click('#nsCapacityForm button');
    await page.waitForFunction(()=>$('nsCapacityMessage').textContent.includes('L/s'),null,{timeout:90000});
    const expected=Number(process.env.ICM_EXPECTED_CAPACITY||'288.094');
    const capacity=Number((await page.locator('#nsCapacityMessage').innerText()).match(/[\d.]+(?= L\/s)/)?.[0]);
    assert(Math.abs(capacity-expected)<.01,'Full pipe capacity agrees with reference case: '+capacity);
    await page.fill('#nsRouteName','Branch review');
    await page.fill('#nsRouteNote','Verify the missing downstream level.');
    await page.click('#nsSaveRoute');
    assert.equal((await snapshot()).routeReviews[0].trials.length,1);
    assert.equal((await snapshot()).routeReviews[0].model.values[0].level,10.25);
    await page.locator('#nsProfilePlot').scrollIntoViewIfNeeded();
    await page.screenshot({path:evidence+'/'+engine+'-long-section.png'});
    await page.reload();
    await page.locator('#nsLongSection').waitFor();
    assert.equal(await page.locator('#nsShowLabels').isChecked(),false);
    await page.click('#nsLongSection');
    await page.selectOption('#nsSavedRoutes','Branch review');
    assert.equal(await page.inputValue('#nsRouteNote'),'Verify the missing downstream level.');
    assert.match(await page.locator('#nsSavedCapacity').innerText(),/600/);
    assert.equal((await snapshot()).monitorLocations.length,3);
    await page.setInputFiles('#nsLoadInput',file('network-revised.csv',nativeNetwork.replace('320,0,9','320,0,9.1')));
    await page.locator('#nsContextUnits').check();await page.click('#nsContextApply');
    assert.equal((await snapshot()).monitorLocations.length,3);
    await page.click('#nsLongSection');await page.selectOption('#nsSavedRoutes','Branch review');
    assert.match(await page.locator('#nsRouteSavedMessage').innerText(),/geometry or route has changed/);
  }
  assert.deepEqual(errors,[]);
  privacy.assertClean();
  console.log(JSON.stringify({engine,baseline,startupMs:Math.round(startup),firstSchematicMs:Math.round(firstSchematic)}));
}finally{await browser.close();}
