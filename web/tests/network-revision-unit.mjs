import assert from 'node:assert/strict';
import '../assets/network-schematic-core.js';
import {baseline,changed} from './network-revision-fixture.mjs';
const c=globalThis.ICMNetworkCore,format='icm-csv-v1';
const source=text=>c.importNativeContext([{name:'network.csv',text}]).network;
const current=c.applyContextRevision(c.empty(),source(baseline),format);
const upstream=current.nodes.find(node=>node.id==='A'),stable=current.nodes.find(node=>node.id==='D');
upstream.name='Working label';
upstream.x=1000;
upstream.applied={signature:'previous',rows:[]};
upstream.monitorId='FM01';
stable.applied={signature:'stable',rows:[]};
const original=current.edges.find(edge=>edge.from==='A');
original.seriesLinks=[{sourceId:'series',sourceName:'fixture.csv',sha256:'synthetic',column:'flow'}];
const unchanged=c.revisionChanges(current,source(baseline));
assert.equal(unchanged.rows.length,0,'A local layout and label edit is separate from source changes');
const diff=c.revisionChanges(current,source(changed));
const a=diff.rows.find(row=>row.id==='A');
assert.equal(a.status,'Modified');
assert.equal(a.monitorReview,true);
assert.equal(a.evidenceReview,true);
assert(a.changes.some(field=>field.category==='Geometry'));
assert(a.changes.some(field=>field.field==='ground_level'));
assert(diff.rows.find(row=>row.id==='C').changes.some(field=>field.category==='Classification'));
const link=diff.rows.find(row=>row.id===original.id&&row.kind==='edge');
assert.equal(link.status,'Modified');
assert(link.changes.some(({field,before,after})=>field==='Downstream node'&&before==='B'&&after==='C'));
assert(link.evidenceReview);
assert.equal(diff.rows.find(row=>row.id==='E').status,'Removed');
assert.equal(diff.rows.find(row=>row.id==='F').status,'Added');
assert.equal(diff.rows.some(row=>row.id==='D'),false);
const revised=c.applyContextRevision(current,source(changed),format);
assert.equal(revised.nodes.find(node=>node.id==='A').x,1000);
assert.equal(revised.nodes.find(node=>node.id==='A').name,'Working label');
assert.equal(revised.nodes.find(node=>node.id==='A').applied,undefined);
assert.equal(revised.nodes.find(node=>node.id==='D').applied.signature,'stable');
assert.equal(revised.edges.find(edge=>edge.id===original.id).seriesLinks,undefined);
assert.equal(current.nodes.find(node=>node.id==='A').applied.signature,'previous');
console.log('Typed revision, source geometry and endpoints, original fields, monitor/source review and scoped stale results passed.');
