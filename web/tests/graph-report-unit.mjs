import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync('web/assets/runtime.release.js','utf8').replace(/start\(\);\s*$/,'');
const sandbox={window:{},document:{getElementById:()=>null,querySelector:()=>null},console,setTimeout,clearTimeout};
vm.createContext(sandbox);vm.runInContext(source,sandbox);
const run=code=>vm.runInContext(code,sandbox);
const layout=run(`hydraulicGraphLayout({fdvMode:true,quantities:['flow','depth','velocity'],hasRain:true,rainMax:66,statistics:[{role:'Observed',statistics:{quantity:'flow',unit:'m³/s'}},{role:'Observed',statistics:{quantity:'depth',unit:'m'}},{role:'Observed',statistics:{quantity:'velocity',unit:'m/s'}},{role:'Rainfall',statistics:{quantity:'rainfall',unit:'mm/h'}}]})`);
assert(layout.yaxis4.domain[1]<layout.yaxis.domain[0]);
assert(layout.yaxis.domain[1]<layout.yaxis3.domain[0]);
assert(layout.yaxis3.domain[1]<layout.yaxis2.domain[0]);
assert.equal(layout.yaxis2.range[1],0);
assert.equal(layout.xaxis.rangeslider.visible,false);
assert.equal(layout.yaxis3.title.text,'Flow (m³/s)');
assert(!layout.yaxis3.overlaying);
const stats=run(`graphStatisticsHtml([{role:'Rainfall',label:'RG <script>',factor:0,statistics:{unit:'mm/h',minimum:1,maximum:12,mean:6,total:85,total_unit:'mm',valid_support_seconds:3600,coverage_fraction:.5,status:'partial'}}])`);
assert(stats.includes('RG &lt;script&gt;'));
assert(stats.includes('0 mm'));
assert(stats.includes('50%'));
assert(stats.includes('raw statistics'));
const figure=run(`reportPlotFigure('test',[{name:'</script><script>bad</script>',x:[null,'2026-01-01'],y:[null,1]}],hydraulicGraphLayout(),[],'A')`);
assert(!figure.includes('<script>bad'));
assert(figure.includes('\\u003c/script>'));
assert(figure.includes('application/json'));
assert(figure.includes('Graph statistics'));
console.log('Graph/report regressions passed: stacked domains, units, no slider, zero scale, support and safe interactive payload.');
