import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium,firefox} from 'playwright';
import {browserLaunchOptions,browserContextOptions} from './browser-environment.mjs';
import {installPrivacyGuard} from './privacy-network.mjs';

const engine=process.env.ICM_BROWSER||'chromium';
const base=process.env.ICM_BASE_URL||'http://127.0.0.1:8000/';
const browser=await (engine==='firefox'?firefox:chromium).launch(browserLaunchOptions());
const context=await browser.newContext({...browserContextOptions(),viewport:{width:1440,height:1000},acceptDownloads:true});
const guard=installPrivacyGuard(context,base),page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));

try {
  await guard.navigate(page,base);
  await page.locator('button[data-workspace="spills"]').click();
  await page.getByRole('tab',{name:'Storage routing',exact:true}).click();
  const panel=page.locator('#tab-storage-routing');
  const inflow=panel.getByLabel('Inflow series'),status=panel.getByRole('status');
  const capacities=panel.getByLabel('Storage capacities (m³, comma-separated)');
  const calculate=panel.getByRole('button',{name:'Calculate',exact:true});
  const save=panel.getByRole('button',{name:'Download calculation CSV'});
  await panel.getByText('Import an eligible instantaneous flow series',{exact:false}).waitFor();
  assert.match(await panel.innerText(),/Import an eligible instantaneous flow series/);
  await panel.getByRole('button',{name:'Open Storage assessment'}).click();
  await page.locator('#runStorageBtn').waitFor();
  await page.getByRole('tab',{name:'Storage routing',exact:true}).click();
  await panel.getByRole('button',{name:'Open Time series'}).click();
  const csv='Timestamp,Flow (L/s)\n2025-01-01 00:00:00,0\n2025-01-01 00:00:10,2000\n2025-01-01 00:00:30,1000\n';
  await page.setInputFiles('#fileInput',{name:'synthetic-storage.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await page.waitForFunction(()=>window.__ICM_WORKBENCH__.stateSummary().readyFiles===1,null,{timeout:90000});
  await page.locator('button[data-workspace="spills"]').click();
  await page.getByRole('tab',{name:'Storage routing',exact:true}).click();
  await inflow.selectOption({index:1});
  await capacities.fill('0, .5, 1');
  await panel.getByLabel('Initial occupied storage (m³)').fill('0');
  await panel.getByLabel('Pass-forward limit (m³/s)').fill('1');
  await panel.getByLabel('Maximum supported timestep (s)').fill('10');
  await panel.getByRole('checkbox').check();
  await panel.getByLabel('Assumption or review note').fill('=Synthetic continuity case');
  await calculate.click();
  await status.filter({hasText:'Partial period'}).waitFor({timeout:60000});
  const table=panel.getByRole('table',{name:'Storage capacity options'});
  assert.deepEqual((await table.locator('tbody tr').allTextContents()).map(text=>text.includes('7.5')),[true,true,true]);
  const rows=await table.locator('tbody tr').evaluateAll(items=>items.map(row=>[...row.cells].slice(0,3).map(cell=>cell.textContent)));
  assert.deepEqual(rows,[['0','2.5','0'],['0.5','2','0.5'],['1','1.5','1']]);
  await panel.getByRole('img',{name:'Routed spill volume'}).waitFor();
  const exportEvent=page.waitForEvent('download');
  await save.click();
  const exported=await fs.readFile(await (await exportEvent).path(),'utf8');
  assert.match(exported,/"Source SHA-256","[a-f0-9]{64}"/);
  assert.match(exported,/"Review note","'=Synthetic continuity case"/);
  await panel.getByLabel('Period end (optional, exact sample)').fill('2025-01-01T00:00:10');
  assert(await save.isDisabled());
  await calculate.click();
  await status.filter({hasText:'completed for the selected period'}).waitFor();
  await capacities.fill('1,0');
  await calculate.click();
  await status.filter({hasText:'strictly increasing'}).waitFor();
  assert(await save.isDisabled());
  assert.deepEqual(errors,[]);
  guard.assertClean();
  console.log('STORAGE_ROUTING_PASS '+engine);
} finally {await browser.close();}
