import vm from 'node:vm';import fs from 'node:fs';import assert from 'node:assert/strict';
const week=(start,end,rag)=>({start,end,week_ending:end,rag});
const a=week('2026-09-07','2026-09-13','Red'),b=week('2026-09-14','2026-09-20','Green');
const survey={batchSignature:'source-a',reviews:{},batch:{monitors:[{monitor:'FM01',status:'complete',weekly:{weeks:[a,b]}}],network:{gauge_summary:[{gauge:'RG01',status:'Amber'}],gauge_weekly:[{...a,gauge:'RG01'}]}}};
let fresh=true;
const sandbox={window:{__ICM_WORKBENCH__:{survey,surveyFresh:()=>fresh}},document:{getElementById:()=>null},console};
let source=fs.readFileSync('web/assets/workflow-26.js','utf8').replace('  ensureUi();','').replace('    renderAssessmentSchematics();','').replace(/  renderAll\(\);\s*\}\)\(\);\s*$/,'})();');
vm.createContext(sandbox);vm.runInContext(source,sandbox);
const api=sandbox.window.__ICM_WORKBENCH__.workflow26;
const keyA=api.weekKey('FM01',a),keyB=api.weekKey('FM01',b);
assert.notEqual(keyA,keyB);
assert.throws(()=>api.applyWeeklyReview('monitor-week','FM01',keyA,'auto','Inspection completed.',''),/name or initials/);
assert.throws(()=>api.applyWeeklyReview('monitor-week','FM01',keyA,'Green','','AS'),/engineering reason/);
api.applyWeeklyReview('monitor-week','FM01',keyA,'Amber','Tidal impact noted.','AS');
assert.equal(api.reviewedWeekState('monitor-week','FM01',a).reviewed,'Amber');
assert.equal(api.reviewedWeekState('monitor-week','FM01',b).reviewed,'Green');
assert.equal(a.rag,'Red');assert.equal(api.reviewedMonitorState(survey.batch.monitors[0]).reviewed,'Amber');
api.applyWeeklyReview('monitor-week','FM01',keyB,'auto','Pumping influence noted.','BS');
assert.equal(survey.reviews['monitor-week:'+keyB].use_calculated,true);
assert.equal(survey.reviews['monitor-week:'+keyA].reviewer,'AS');
assert.equal(survey.reviews['monitor-week:'+keyB].reviewer,'BS');
api.applyWeeklyReview('monitor-week','FM01',keyA,'Green','Site visit confirms the signal.','CS');
assert.equal(survey.reviews['monitor-week:'+keyA].history[0].reviewer,'AS');
fresh=false;
assert.equal(api.reviewedWeekState('monitor-week','FM01',a).reviewed,'Red');
assert.equal(api.reviewedWeekState('monitor-week','FM01',a).historical_review,true);
assert.throws(()=>api.applyWeeklyReview('monitor-week','FM01',keyA,'Amber','note','AS'),/Re-run/);
fresh=true;survey.batchSignature='source-b';
assert.equal(api.reviewedWeekState('monitor-week','FM01',a).reviewed,'Red');
survey.batchSignature='source-a';a.rag='Amber';
assert.equal(api.reviewedWeekState('monitor-week','FM01',a).reviewed,'Amber');
const beforeRevertEvents=survey.reviewLedger.length;
api.revertReview('monitor-week',keyA,'CS');
assert.equal(survey.reviews['monitor-week:'+keyA],undefined);
assert.equal(survey.reviews['monitor-week:'+keyB].reason,'Pumping influence noted.');
assert.equal(survey.reviewLedger.length,beforeRevertEvents+1);
assert.equal(survey.reviewLedger.at(-1).event_type,'reverted_to_calculated');
assert.equal(survey.reviewLedger.at(-1).reviewer,'CS');
assert.equal(survey.reviewLedger.filter(e=>e.subject===keyA).some(e=>e.event_type==='review_created'),true);
assert.equal(survey.reviewLedger.filter(e=>e.subject===keyA).some(e=>e.event_type==='review_updated'),true);
const matrixHtml=api.weekMatrixHtml('monitor-week');
assert(matrixHtml.includes('FM01'));
assert(matrixHtml.includes('data-matrix-cell'));
assert(matrixHtml.includes('w26-matrix-review-mark'));
const exceptions=api.exceptionQueue('monitor-week');
assert(exceptions.some(item=>item.name==='FM01'));
api.selectReviewWeek('monitor-week','FM01',keyB);
assert.equal(survey.reviewContext.name,'FM01');
assert.equal(survey.reviewContext.weekKey,keyB);
assert.throws(()=>api.applyWeeklyReview('monitor-week','FM02',keyB,'auto','note','AS'),/not present/);
assert.throws(()=>api.applyWeeklyReview('monitor-week','FM01',keyB,'Purple','note','AS'),/valid weekly/);
const gauge=survey.batch.network.gauge_weekly[0],gaugeKey=api.weekKey('RG01',gauge);
api.applyWeeklyReview('gauge-week','RG01',gaugeKey,'Green','Logger inspected.','RG');
assert.equal(api.reviewedGaugeState(survey.batch.network.gauge_summary[0]).reviewed,'Green');
api.saveMonitorComment('FM01','Known tidal influence.','AS');
assert.equal(survey.monitorComments.FM01.text,'Known tidal influence.');
const commentEvents=survey.commentLedger.length;
api.clearMonitorComment('FM01','AS');
assert.equal(survey.monitorComments.FM01,undefined);
assert.equal(survey.commentLedger.length,commentEvents+1);
assert.equal(survey.commentLedger.at(-1).event_type,'comment_cleared');
console.log('Weekly review regressions passed: isolated weeks/authors, immutable calculated evidence, append-only review/comment ledgers, stale inputs, revert and gauge reviews.');
