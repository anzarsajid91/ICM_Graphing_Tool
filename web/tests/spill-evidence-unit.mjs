import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const nodes=new Map(['timeBasisConfirmed','levelDatumConfirmed'].map(id=>[id,{checked:true,addEventListener(){}}]));
const sandbox={console,window:{__ICM_WORKBENCH__:{}},document:{getElementById:id=>nodes.get(id)||null,querySelector:()=>null},setTimeout,clearTimeout};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('web/assets/runtime.release.js','utf8').replace(/start\(\);\s*$/,''),sandbox);
const overlay=fs.readFileSync('web/assets/workbench-v2.js','utf8');
vm.runInContext(overlay.slice(overlay.indexOf('  function annualRows('),overlay.indexOf('  async function v2RunSpills(')),sandbox);
const run=code=>vm.runInContext(code,sandbox);
run(`
  const row={year:2025,spill_count:100,duration_hours:200,valid_hours:8760,unknown_hours:0,excluded_hours:0,requested_hours:8760,analysis_start:'2025-01-01T00:00:00',analysis_end:'2026-01-01T00:00:00',count_status:'definitive'};
  const month={...row,month:1,valid_hours:744,requested_hours:744,analysis_end:'2025-02-01T00:00:00'};
  state.spills={observed:{analysis_start:'2024-01-01',analysis_end:'2026-01-01',yearly_summary:[row],monthly_summary:[month]},model:{analysis_start:'2025-01-01',analysis_end:'2027-01-01',yearly_summary:[{...row,spill_count:107,duration_hours:230}],monthly_summary:[{...month,spill_count:104,duration_hours:230}]}};
`);
let html=run('annualComparison()');
assert(html.includes('spill-rag-amber'));
assert(html.includes('spill-rag-red'));
assert(html.includes('spill-month-green'));
assert(html.includes('spill-month-red'));
assert(!html.includes('<th>Count deviation</th>'));
assert(!html.includes('<th>Duration deviation</th>'));
assert(!html.includes('summary-box'));
assert(html.includes('<th>Jan</th>')&&html.includes('<th>Dec</th>'));
assert.equal(run('spillDeviationRag(null,0).rag'),null);
assert.equal(run('spillDeviationRag(0,0).rag'),'Green');
assert.equal(run('spillDeviationRag(0,1).rag'),'Red');
run('state.spills.model.yearly_summary[0].unknown_hours=1');
assert(run('annualComparison()').includes('unexcluded unknown coverage'));
run('state.spills.model.yearly_summary[0].unknown_hours=0; state.spills.model.exclusion_audit=[{start:"2025-03-01",end:"2025-03-02"}]');
assert(run('annualComparison()').includes('exclusion masks differ in this period'));
run('state.spills.model.exclusion_audit=[]');
nodes.get('timeBasisConfirmed').checked=false;
assert(run('annualComparison()').includes('Confirm that observed and modelled sources share'));
nodes.get('timeBasisConfirmed').checked=true;
assert(run('annualTable(state.spills.observed)').includes('Yearly spill summary'));
assert(!run('annualTable(state.spills.observed)').includes('<th>Status</th>'));
console.log('Spill evidence regressions passed: independent common-year RAG, missing values, gap and exclusion withholding, compact tables and Jan–Dec comparisons.');
